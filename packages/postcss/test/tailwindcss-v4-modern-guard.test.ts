import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateTailwindV4Style } from '@weapp-tailwindcss/engine'
import postcss from 'postcss'
import { describe, expect, it } from 'vitest'
import { isTailwindcssV4ModernCheck } from '../src/compat/tailwindcss-v4/modern-syntax'
import { createStyleHandler } from '../src/index'
import { postcssWeappTailwindcssPrePlugin } from '../src/plugins/pre'

function modernGuard(marginTrim: string) {
  return `((-webkit-hyphens: none) and (not (margin-trim: ${marginTrim}))) or ((-moz-orient: inline) and (not (color: rgb(from red r g b))))`
}

function isModernGuard(params: string, name = 'supports') {
  return isTailwindcssV4ModernCheck(new postcss.AtRule({ name, params }))
}

describe('Tailwind CSS v4 modern guard', () => {
  it.each(['inline', 'block'])('recognizes the complete margin-trim value %s with either spacing', (value) => {
    const params = modernGuard(value)
    expect(isModernGuard(params)).toBe(true)
    expect(isModernGuard(params.replaceAll(': ', ':'))).toBe(true)
  })

  it.each(['inline-start', 'inline-end', 'block-start', 'block-end', 'inlineblock', 'blocker', 'inline block', 'block inline', 'none'])('does not recognize the different margin-trim value %s', (value) => {
    expect(isModernGuard(modernGuard(value))).toBe(false)
  })

  it.each(['inline', 'block'])('requires the margin-trim property for %s rather than a custom property with the same suffix', (value) => {
    expect(isModernGuard(modernGuard(value).replace('margin-trim:', '--margin-trim:'))).toBe(false)
  })

  it.each([
    ['-webkit-hyphens: none', 'display: grid'],
    ['margin-trim: block', 'display: grid'],
    ['-moz-orient: inline', 'display: grid'],
    ['color: rgb(from red r g b)', 'color: red'],
  ])('keeps all four probe conditions: %s', (probe, replacement) => {
    expect(isModernGuard(modernGuard('block').replace(probe, replacement))).toBe(false)
  })

  it('only recognizes supports at-rules', () => {
    expect(isModernGuard(modernGuard('block'), 'media')).toBe(false)
    expect(isModernGuard('(margin-trim: block)')).toBe(false)
  })

  it.each(['inline', 'block'])('unwraps %s fallback initializers without dropping declarations', async (value) => {
    const input = `@layer properties { @supports ${modernGuard(value)} { *, ::before, ::after { --tw-shadow: 0 0 #0000; } } }`
    const { root, css } = await postcss([postcssWeappTailwindcssPrePlugin({})]).process(input, { from: undefined })
    const shadowDeclarations: string[] = []
    root.walkDecls('--tw-shadow', (decl) => {
      expect(decl.parent?.parent?.type).toBe('root')
      shadowDeclarations.push(decl.value)
    })
    expect(shadowDeclarations).toEqual(['0 0 #0000'])
    expect(css).not.toContain('@supports')
    expect(css).not.toContain('@layer')
  })

  it('preserves unrelated conditional rules', async () => {
    const params = modernGuard('block-start')
    const input = `@layer properties { @supports ${params} { .author { --author-value: 1; } } }`
    const { css } = await postcss([postcssWeappTailwindcssPrePlugin({})]).process(input, { from: undefined })
    expect(css).toContain(`@supports ${params}`)
    expect(css).toContain('--author-value: 1')
  })

  it('unwraps the block guard generated by Tailwind CSS 4.3.4 in the real style pipeline', async () => {
    const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
    const generated = await generateTailwindV4Style({
      projectRoot,
      css: '@import "tailwindcss" source(none);',
      candidates: ['shadow-sm', 'translate-x-1'],
    })
    expect(generated.css).toContain('margin-trim: block')
    const styleHandler = createStyleHandler({ majorVersion: 4, isMainChunk: true })
    const { css } = await styleHandler(generated.css)
    const root = postcss.parse(css)
    const initializers: string[] = []
    root.walkDecls('--tw-translate-y', (decl) => {
      expect(decl.parent?.parent?.type).toBe('root')
      initializers.push(decl.value)
    })
    expect(initializers).toEqual(['0'])
    expect(css).not.toContain('margin-trim')
    expect(css).not.toContain('@layer')
    expect(css).toContain('.shadow-sm')
    expect(css).toContain('.translate-x-1')
  })
})
