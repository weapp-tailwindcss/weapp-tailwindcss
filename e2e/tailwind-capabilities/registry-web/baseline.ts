export function registryBaseline(properties: UtilityInventoryEntry['declarations']) {
  return properties.flatMap(({ property, value }) => {
    const options = alternatives.find(([pattern]) => pattern.test(property))?.[1]
    // font-stretch 的历史关键词按百分比计算；比较规范值避免 condensed 与 75% 成为同一基线。
    const normalized = property === 'font-stretch'
      ? ({ 'ultra-condensed': '50%', 'extra-condensed': '62.5%', 'condensed': '75%', 'semi-condensed': '87.5%', 'normal': '100%', 'semi-expanded': '112.5%', 'expanded': '125%', 'extra-expanded': '150%', 'ultra-expanded': '200%' } as Record<string, string>)[value] ?? value
      : value
    return options ? [`${property}:${options.find(option => option !== normalized) ?? options[0]};`] : []
  }).join('')
}
